export function teamSpawn(team: 1 | 2, slot: number) {
  const [x, y, z, yaw] = starts[team][slot % starts[team].length]
  const center = { x, y, z }
  const floor = mapDistance(center, { x: 0, y: -1, z: 0 }, 3)
  if (floor === 3) throw new Error('Dust2 team spawn has no floor')
  return { position: { x, y: y - floor + 0.08, z }, yaw }
}
